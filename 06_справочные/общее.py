#!/usr/bin/env python3
"""Общие функции инструментов архива dubina-arhiv.

Зачем этот файл существует. `tracker_stats()` была скопирована в два скрипта —
`числа_readme.py` и `актуализация_снимка.py`. Копии обязаны считать одинаково:
иначе число этапов и поддействий трекера в документах и в СВЕРКЕ считалось бы
двумя способами и могло разойтись, а расхождение ничем не обнаруживалось.

Сверка 03.10.2026 показала, что копии совпадают побайтово, кроме docstring.
Но две копии одной логики — это мина: правка одной не правит другую. Теперь
логика одна, и оба скрипта берут её отсюда.

Если сюда что-то добавляется, правило то же: только то, что обязано считаться
одинаково в нескольких инструментах. Раздувать этот файл до общей свалки
не нужно.
"""
import re


def tracker_stats(path):
    """Число этапов и поддействий трекера прямо из разметки, без ручных констант.

    Этапы — вхождения `{n:'`, поддействия — объекты вида `{ t:'…', done:true|false }`.
    Считается из самой разметки, а не хранится константой, чтобы число не могло
    отстать от содержимого файла.
    """
    text = path.read_text(encoding="utf-8")
    steps = len(re.findall(r"\{n:'", text))
    actions = len(re.findall(r"\{\s*t:'[^']*'\s*,\s*done:(?:true|false)\s*\}", text))
    return steps, actions
